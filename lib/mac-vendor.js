const ATHOM_OUI = [
  '9013DAA81559',
].join('');

function unpack(blob) {
  const set = new Set();
  for (let i = 0; i < blob.length; i += 6) set.add(blob.slice(i, i + 6));
  return set;
}

const VENDORS = [
  ['Huawei', unpack(HUAWEI_OUI)],
  ['Athom',  unpack(ATHOM_OUI)],
];

/**
 * Accepts the shapes a MAC arrives in — "b0:c7:87:ee:95:12", "B0-C7-87-EE-95-12",
 * "b0c787ee9512" — and returns the lowercase colon form, or null if it is not a MAC.
 * Homey documents getMAC() as returning a string and says nothing about the separator or
 * about what comes back for an address nobody answered for, so nothing here assumes.
 */
function normalizeMac(mac) {
  if (typeof mac !== 'string') return null;
  const hex = mac.replace(/[^0-9a-fA-F]/g, '').toLowerCase();
  if (hex.length !== 12) return null;
  if (/^0+$/.test(hex)) return null; // 00:00:00:00:00:00 is "no answer", not a device
  return hex.match(/.{2}/g).join(':');
}

/** The first three bytes, uppercase and without separators: "B0C787". */
function ouiOf(mac) {
  const norm = normalizeMac(mac);
  return norm ? norm.replace(/:/g, '').slice(0, 6).toUpperCase() : null;
}

/**
 * True when the MAC was made up by the device rather than assigned by the IEEE — the
 * "locally administered" bit. Phones randomise their MAC per network this way. Such a MAC
 * carries no manufacturer at all, so reporting a vendor for it would be inventing one.
 */
function isLocallyAdministered(mac) {
  const norm = normalizeMac(mac);
  if (!norm) return false;
  return (parseInt(norm.slice(0, 2), 16) & 0x02) !== 0;
}

/**
 * The manufacturer's name, or null when the prefix is not one we carry.
 *
 * The locally-administered check below is belt and braces, not load-bearing: the IEEE only
 * assigns prefixes with that bit clear, so none of the 2080 in this file can ever have it
 * set and a randomised MAC therefore fails the set lookup anyway. It is spelled out because
 * the intent matters — a made-up MAC has no manufacturer, and someone reading only the set
 * lookup could not tell whether that was decided or merely fell out.
 */
function vendorOf(mac) {
  if (isLocallyAdministered(mac)) return null;
  const oui = ouiOf(mac);
  if (!oui) return null;
  for (const [name, set] of VENDORS) {
    if (set.has(oui)) return name;
  }
  return null;
}

/**
 * Everything worth showing about one MAC, in one object, with the unknown cases separated:
 * "no MAC came back" is not "a MAC we do not recognise", and neither is "a MAC that is not
 * a manufacturer's to begin with".
 */
function describeMac(mac) {
  const norm = normalizeMac(mac);
  if (!norm) return { mac: null, oui: null, vendor: null, local: false };
  const local = isLocallyAdministered(norm);
  return { mac: norm, oui: ouiOf(norm), vendor: local ? null : vendorOf(norm), local };
}

