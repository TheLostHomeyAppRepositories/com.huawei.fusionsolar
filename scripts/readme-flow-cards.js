'use strict';

// The flow-card tables in README.md, built from app.json.
//
// They were written by hand and fell behind: by 1.2.324 a third of the cards were missing,
// several had been renamed, and token lists no longer matched (README review 2026-10-10).
// The card's own hint — the text Homey shows behind the (i) — is the description, so the
// README says what the app says and a change has one place to be made.
//
//   node scripts/readme-flow-cards.js           prints the section
//   node scripts/readme-flow-cards.js --write   replaces it in README.md
//
// test/readme-flow-cards.test.js fails when README.md and app.json disagree.

const fs   = require('fs');
const path = require('path');

const ROOT   = path.join(__dirname, '..');
const START  = '<!-- flow-cards:start — generated by scripts/readme-flow-cards.js from app.json; edit the card hints there -->';
const END    = '<!-- flow-cards:end -->';

// The order of the Devices section, so the tables read in the same order as the README.
const DRIVER_ORDER = [
  'fusionsolar_kiosk',
  'sun2000_openapi_fusionsolar', 'luna2000_openapi_fusionsolar', 'powermeter_openapi_fusionsolar',
  'isitepower_solar_openapi_fusionsolar', 'isitepower_battery_openapi_fusionsolar',
  'isitepower_grid_openapi_fusionsolar', 'isitepower_home_openapi_fusionsolar',
  'sdongle_a_modbus', 'sun2000_modbus', 'sun2000_emma_modbus',
  'luna2000_modbus', 'luna2000_emma_modbus', 'dtsu666_modbus', 'powermeter_emma_modbus',
  'smartcharger_emma_modbus', 'smartcharger_ocpp', 'easee_ocpp', 'energy_management',
];

function driversOf(card) {
  const dev = (card.args || []).find((a) => a.type === 'device');
  if (!dev) return card.id.startsWith('ems_') ? ['energy_management'] : [];
  // Both spellings occur: "driver_id=a|b" and "driver_id=a|driver_id=b".
  const part = (dev.filter || '').split('&').find((p) => p.startsWith('driver_id='));
  return part ? part.split('|').map((s) => s.replace(/^driver_id=/, '')).filter(Boolean) : [];
}

function rank(drivers) {
  const r = drivers.map((d) => DRIVER_ORDER.indexOf(d)).filter((i) => i >= 0);
  return r.length ? Math.min(...r) : DRIVER_ORDER.length;
}

// "Battery LUNA 2000 (Modbus)" + "Battery LUNA 2000 (EMMA Modbus)" → "Battery LUNA 2000 (Modbus / EMMA Modbus)"
function deviceLabel(app, drivers) {
  const names = drivers
    .slice().sort((a, b) => DRIVER_ORDER.indexOf(a) - DRIVER_ORDER.indexOf(b))
    .map((id) => (app.drivers.find((d) => d.id === id) || { name: { en: id } }).name.en);
  const byFamily = new Map();
  for (const n of names) {
    const m = /^(.*?) \((.*)\)$/.exec(n);
    const fam = m ? m[1] : n;
    if (!byFamily.has(fam)) byFamily.set(fam, []);
    if (m) byFamily.get(fam).push(m[2]);
  }
  return [...byFamily].map(([fam, kinds]) => (kinds.length ? `${fam} (${kinds.join(' / ')})` : fam)).join(', ');
}

const cell  = (s) => String(s).replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim();
const title = (card) => cell(card.title.en.replace(/!\{\{([^|}]*)\|([^}]*)\}\}/g, '$1 / $2'));

function build(app) {
  const live = (kind) => app.flow[kind]
    .filter((c) => !c.deprecated)
    .map((c, i) => ({ c, i, drivers: driversOf(c) }))
    .sort((a, b) => (rank(a.drivers) - rank(b.drivers)) || (a.i - b.i));

  const out = [START, ''];
  out.push('Every card the app offers, with the text Homey shows behind its (i). Retired cards are left',
    'out — they are no longer offered for new flows, and existing flows keep working.', '');

  out.push('### Triggers', '', '| Card | Device | Tokens | Description |', '|---|---|---|---|');
  for (const { c, drivers } of live('triggers')) {
    const tokens = (c.tokens || []).map((t) => `\`${t.name}\``).join(', ') || '–';
    out.push(`| ${title(c)} | ${cell(deviceLabel(app, drivers))} | ${tokens} | ${cell(c.hint.en)} |`);
  }

  out.push('', '### Conditions', '', '| Card | Device | Description |', '|---|---|---|');
  for (const { c, drivers } of live('conditions')) {
    out.push(`| ${title(c)} | ${cell(deviceLabel(app, drivers))} | ${cell(c.hint.en)} |`);
  }

  out.push('', '### Actions');
  let group = null;
  for (const { c, drivers } of live('actions')) {
    const label = deviceLabel(app, drivers) || 'App';
    if (label !== group) {
      group = label;
      out.push('', `#### ${label}`, '', '| Card | Description |', '|---|---|');
    }
    out.push(`| ${title(c)} | ${cell(c.hint.en)} |`);
  }
  out.push('', END);
  return out.join('\n');
}

function readApp() {
  return JSON.parse(fs.readFileSync(path.join(ROOT, 'app.json'), 'utf8'));
}

/** The README with its generated section replaced; throws when the markers are missing. */
function render(readme, app = readApp()) {
  const crlf = readme.includes('\r\n');
  const text = readme.replace(/\r\n/g, '\n');
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error('README.md has no flow-cards markers');
  const next = text.slice(0, a) + build(app) + text.slice(b + END.length);
  return crlf ? next.replace(/\n/g, '\r\n') : next;
}

module.exports = { build, render, START, END };

if (require.main === module) {
  if (process.argv.includes('--write')) {
    const file = path.join(ROOT, 'README.md');
    fs.writeFileSync(file, render(fs.readFileSync(file, 'utf8')));
    console.log('README.md flow cards updated');
  } else {
    process.stdout.write(build(readApp()) + '\n');
  }
}
